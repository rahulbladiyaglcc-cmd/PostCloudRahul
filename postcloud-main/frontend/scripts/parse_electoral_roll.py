def clean_line_hindi(line):
    line = re.sub(r'लसग', 'सिंह', line)
    line = re.sub(r'सहमल|स्त्रीगल', 'सहगल', line)
    line = re.sub(r'दरपकद', 'दीपेन्द्र', line)
    line = re.sub(r'दरपक', 'दीपक', line)
    line = re.sub(r'दलपक', 'दीपक', line)
    line = re.sub(r'कनवर', 'कंवर', line)
    line = re.sub(r'इमरपन', 'इमरान', line)
    line = re.sub(r'अ\.यसब', 'अय्यूब', line)
    line = re.sub(r'अ\.नरतप', 'अनिता', line)
    line = re.sub(r'अ\.नेमीतप', 'अमिता', line)
    line = re.sub(r'अ\.नदकत', 'अंकित', line)
    line = re.sub(r'अ\.नमत', 'अमित', line)
    line = re.sub(r'ममतप', 'ममता', line)
    line = re.sub(r'गरतप', 'गीता', line)
    line = re.sub(r'नशव', 'शिव', line)
    line = re.sub(r'गयठररल|गयठवपल', 'गोठवाल', line)
    line = re.sub(r'कपशररहर', 'कुशवाहा', line)
    line = re.sub(r'मटनपगर', 'भटनागर', line)
    line = re.sub(r'कनपल', 'कपिल', line)
    line = re.sub(r'नरजक', 'नायक', line)
    line = re.sub(r'नपजसकर', 'पुष्पा', line)
    line = re.sub(r'शशफरलल', 'शैफाली', line)
    line = re.sub(r'जशसरल', 'जयश्री', line)
    line = re.sub(r'ररम ककषण', 'राम कृष्ण', line)

    tokens = re.findall(r'[\u0900-\u097F]+|[A-Za-z0-9/-]+', line)
    cleaned = []
    for t in tokens:
        if re.match(r'[\u0900-\u097F]+', t):
            if t in HINDI_DICT:
                cleaned.append(HINDI_DICT[t])
            else:
                replaced = t
                for orig, repl in sorted(HINDI_DICT.items(), key=lambda x: -len(x[0])):
                    if orig in replaced:
                        replaced = replaced.replace(orig, repl)
                cleaned.append(replaced)
        else:
            cleaned.append(t)
    return " ".join(cleaned)

def transliterate(hindi_text):
    words = hindi_text.split()
    eng = []
    for w in words:
        eng.append(TRANSLIT.get(w, w))
    return " ".join(eng)

def parse_electoral_roll(pdf_path, id_prefix=""):
    reader = pypdf.PdfReader(pdf_path)
    total_pages = len(reader.pages)
    
    # Header metadata from page 3 (index 2)
    p3 = reader.pages[2].extract_text()
    ward_m = re.search(r'वपरर\s*सनखयप\s*:\s*(\d+)', p3)
    part_m = re.search(r'मपग\s*सनखयप\s*:\s*(\d+)', p3)
    ward = ward_m.group(1) if ward_m else '91'
    part = part_m.group(1) if part_m else '1'
    
    lines_p3 = [l.strip() for l in p3.split('\n') if l.strip()]
    raw_area = ''
    for idx, l in enumerate(lines_p3):
        if 'ननवपरचक नपमपवलर' in l and idx + 1 < len(lines_p3):
            raw_area = lines_p3[idx + 1]
            break
            
    clean_area = clean_line_hindi(raw_area) or f"वार्ड {ward}, भाग {part}"
    
    records = []
    serial = 1
    
    for page_idx in range(2, total_pages):
        page_text = reader.pages[page_idx].extract_text()
        blocks = re.split(r'Photo is\s*Available', page_text)
        
        # Stop if we hit deletion / supplement summary footer on last page
        if 'नरलयपन सपचल' in page_text and len(blocks) < 5:
            pass
            
        for b in blocks:
            epic_m = re.search(r'(RJ/\d{2}/\d{3}/\d{6}|[A-Z]{3}\d{7})', b)
            if not epic_m:
                continue
            epic = epic_m.group(1)
            
            # Age & Gender
            age_m = re.search(r'आयप:\s*(\d+)\s*(पपरष|सर|प|स)', b)
            age = int(age_m.group(1)) if age_m else 30
            gender_raw = age_m.group(2) if age_m else ''
            gender = "Male" if ("प" in gender_raw and "सर" not in gender_raw) else "Female"
            
            lines = [l.strip() for l in b.split('\n') if l.strip()]
            age_idx = -1
            for idx, line in enumerate(lines):
                if 'आयप:' in line:
                    age_idx = idx
                    break
                    
            house_raw = "1"
            name_raw = ""
            relative_raw = ""
            if age_idx != -1 and age_idx + 3 < len(lines):
                house_raw = lines[age_idx + 1]
                name_raw = lines[age_idx + 2]
                relative_raw = lines[age_idx + 3]
            elif age_idx != -1 and age_idx + 2 < len(lines):
                house_raw = lines[age_idx + 1]
                name_raw = lines[age_idx + 2]
                
            house_clean = re.sub(r'[^0-9A-Za-z\u0900-\u097F/-]', '', house_raw) or "1"
            
            full_name_hi = clean_line_hindi(name_raw)
            relative_name_hi = clean_line_hindi(relative_raw)
            
            # Filter out non-voter headers captured accidentally
            if 'नगरननगम' in full_name_hi or 'ननवपरचक' in full_name_hi or not full_name_hi:
                continue
                
            parts_hi = full_name_hi.split()
            first_name_hi = parts_hi[0] if parts_hi else f"मतदाता {serial}"
            last_name_hi = " ".join(parts_hi[1:]) if len(parts_hi) > 1 else ""
            
            first_name_en = TRANSLIT.get(first_name_hi, first_name_hi)
            last_name_en = " ".join([TRANSLIT.get(p, p) for p in parts_hi[1:]]) if len(parts_hi) > 1 else ""
            full_name_en = f"{first_name_en} {last_name_en}".strip()
            relative_name_en = transliterate(relative_name_hi)
            record_id = f"w{ward}_p{part}_{serial}"
            
            search_tokens = " ".join(set([
                first_name_hi.lower(),
                last_name_hi.lower(),
                full_name_hi.lower(),
                relative_name_hi.lower(),
                first_name_en.lower(),
                last_name_en.lower(),
                full_name_en.lower(),
                relative_name_en.lower(),
                epic.lower(),
                str(house_clean).lower(),
                f"मकान {house_clean}",
                f"वार्ड {ward}",
                f"भाग {part}",
                f"ward {ward}",
                f"part {part}",
                clean_area.lower(),
                f"98290{serial:05d}"
            ]))
            
            dob = f"{2026 - age}-01-01"
            
            record = {
                "id": record_id,
                "serialNumber": serial,
                "wardNumber": str(ward),
                "partNumber": str(part),
                "wardPart": f"वार्ड {ward}, भाग {part}",
                "areaName": clean_area,
                "firstName": first_name_hi,
                "lastName": last_name_hi,
                "englishName": full_name_en,
                "englishFirstName": first_name_en,
                "englishLastName": last_name_en,
                "englishRelative": relative_name_en,
                "email": f"voter_{ward}_{part}_{serial}@jaipur-ward{ward}.gov.in",
                "mobileNumber": f"98290{serial:05d}",
                "whatsappNumber": f"98290{serial:05d}",
                "dateOfBirth": dob,
                "gender": gender,
                "aadhaarNumber": f"7{ward:0>3} 8{part:0>3} {serial:0>4}",
                "electionID": epic,
                "houseName": clean_area.split(',')[0],
                "houseNumber": house_clean,
                "streetName": clean_area,
                "streetNumber": f"वार्ड {ward}, भाग {part}",
                "village": "सोडाला",
                "panchayat": "51-सिविल लाईन्स",
                "district": "जयपुर",
                "postOffice": "302019",
                "job": "नागरिक / मतदाता",
                "status": "COMPLETED",
                "lastCompletedStep": 6,
                "createdAt": "2026-01-01T00:00:00.000Z",
                "previousAddress": f"संबंधी: {relative_name_hi}" if relative_name_hi else "",
                "searchTokens": search_tokens,
                "address": {
                    "houseName": clean_area.split(',')[0],
                    "houseNumber": house_clean,
                    "streetName": clean_area,
                    "streetNumber": f"वार्ड {ward}, भाग {part}",
                    "village": "सोडाला",
                    "postOffice": "302019",
                    "locationType": "current"
                },
                "user": {
                    "id": 1,
                    "firstName": "Primary",
                    "lastName": "Admin",
                    "email": "admin@gmail.com"
                }
            }
            records.append(record)
            serial += 1
            
    return {
        "wardNumber": str(ward),
        "partNumber": str(part),
        "areaName": clean_area,
        "total": len(records),
        "male": len([r for r in records if r["gender"] == "Male"]),
        "female": len([r for r in records if r["gender"] == "Female"]),
        "records": records,
        "voters": records
    }

